export default function AtprotoProviderCycle({ className }: { className?: string }) {
  const n = MARKS.length;
  const [i, setI] = useState(0);
  const [animate, setAnimate] = useState(true);

  // Advance one mark every 2s.
  useEffect(() => {
    const id = setInterval(() => setI((v) => v + 1), 2000);
    return () => clearInterval(id);
  }, []);

  // We render one extra frame (a clone of the first mark) so the slide past the
  // last mark lands on it seamlessly; then snap back to 0 with no transition.
  useEffect(() => {
    if (i !== n) return;
    const t = setTimeout(() => {
      setAnimate(false);
      setI(0);
    }, 420);
    return () => clearTimeout(t);
  }, [i, n]);

  // Re-enable the transition on the frame after a snap.
  useEffect(() => {
    if (animate) return;
    const r = requestAnimationFrame(() => setAnimate(true));
    return () => cancelAnimationFrame(r);
  }, [animate]);

  const frames = [...MARKS, MARKS[0]];

  return (
    <span className={`inline-block overflow-hidden align-[-0.15em] ${className ?? ""}`} style={{ height: `${H_EM}em`, width: `${H_EM}em` }} aria-hidden>
      <span
        className={`flex flex-col ${animate ? "transition-transform duration-380 ease-out motion-reduce:transition-none" : ""}`}
        style={{ transform: `translateY(-${i * H_EM}em)` }}
      >
        {frames.map((m, idx) => (
          <svg key={idx} viewBox={m.viewBox} fill="currentColor" className="shrink-0" style={{ height: `${H_EM}em`, width: `${H_EM}em` }} preserveAspectRatio="xMidYMid meet">
            {m.body}
          </svg>
        ))}
      </span>
    </span>
  );
}
