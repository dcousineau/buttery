/**
 * A SECOND dev recipe corpus: 210 recipes swept off the atproto network, kept
 * exactly as their authors wrote them.
 *
 *   pnpm --filter @buttery/web db:seed:run
 *
 * This sits BESIDE `1787000664088_dev_recipes.ts` and does not replace it. The
 * two corpora measure two different things and must not be merged.
 *
 * ── WHY A SECOND CORPUS EXISTS ───────────────────────────────────────────────
 *
 * `1787000664088_dev_recipes.ts` was written to calibrate the ingredient
 * matcher, and it does that job well. But that is exactly what disqualifies it
 * as a *sample*: every line in it was authored or chosen by someone who could
 * see whether it matched. Run `@buttery/food`'s `categorizeWith` over it and the
 * lexicon misses 0 of 396 lines. A 0.0% miss rate is not a measurement of the
 * lexicon, it is a measurement of the corpus.
 *
 * The enrichment plan (`docs/plans/2026-08-20-recipe-enrichment.md` §8.1) needs
 * the real number, because the allergen rules key off it: `not_detected` is
 * emitted ONLY when every line in a recipe resolved, so a recipe with even one
 * unresolved line collapses to `unknown`. Whether that verdict is reachable at
 * all is a question about lines nobody tuned.
 *
 * So this corpus is drawn from `origin='sync'` rows — recipes other people
 * published to their own PDS and the sweep indexed. Nobody involved in writing
 * them had ever seen `packages/food/src/lexicon.json`.
 *
 * ── HOW IT WAS SELECTED, AND WHY THAT MATTERS MOST ──────────────────────────
 *
 * It is a CENSUS, not a sample. Every recipe here is every recipe in the
 * author's dev index that did not come from the one bulk-import account, with
 * no per-recipe discretion exercised at any point.
 *
 * That account matters. The index held 4251 synced recipes, and 4041 of them
 * belong to a single DID: 3695 Wikibooks Cookbook imports (`wb-*` ids) plus 346
 * uniformly machine-styled rows. A uniform random draw over all 4251 would
 * therefore have been 95% one importer's house style. Measured separately, the
 * Wikibooks stratum misses 3.8% of lines and the machine-styled stratum 2.8%,
 * against 12.2% for the 210 recipes here. Choosing a stratum changes the answer
 * by 4x, so the stratum boundary is stated rather than buried, and it was drawn
 * on provenance (which account published it) — never on whether a line matched.
 *
 * Taking the non-bulk stratum WHOLE is the point. A census has no selection step
 * to bias, which is the only structural defence against rebuilding the very
 * corpus that produced the 0%.
 *
 * Nothing here was tidied. Brand names (`Carroll Shelby's Texas Chili Kit`,
 * `Cardini's ceasar dressing`), loanwords (`Butterschmalz`, `Lebkuchengewuerz`,
 * `nam pla`), whole recipes in French and German, unicode fractions, typos
 * (`it's abour 2 cans`), parentheticals, compound lines and section headers all
 * survive verbatim. That mess IS the sample; removing any of it would be
 * measuring the tidying rather than the lexicon.
 *
 * ── WHAT WAS CHANGED, AND WHAT WAS NOT ───────────────────────────────────────
 *
 * This lands in a public repo, so identity was stripped and prose was dropped:
 *
 *   - **Dropped entirely: descriptions and instructions.** Ingredient lists are
 *     largely uncopyrightable facts; headnotes and method prose are not, and
 *     they are also where a personal note would hide. The classifiers read
 *     ingredient lines only, so nothing measurable is lost.
 *   - **DIDs replaced by an opaque author key** (`a01`..`a39`). It is kept, not
 *     discarded, because 210 recipes from 39 authors is not 210 independent
 *     draws — the per-author clustering is real and someone re-running this
 *     needs to be able to see it.
 *   - **Four titles carrying a private individual's given name** were
 *     generalised ("Aunt Linda's Rosemary Pecans" → "Rosemary Pecans"). No
 *     ingredient line is touched by that, so no measured number moves.
 *   - **Two ingredient lines carried a record locator** — one an `at://` URI
 *     with a DID in it, one a `recipe.exchange` permalink. Both were replaced
 *     with same-shaped placeholders, and both were checked to parse and match
 *     identically before and after (`en:coating` and `en:pesto` respectively).
 *
 * NO recipe was dropped. Not one — including 38 rows from a single author whose
 * entire ingredient list is the literal string "See original recipe", and one
 * "Test Recipe" whose only ingredient is "Love". Those are bookmarks rather than
 * recipes and they are automatic 100%-miss rows, but they are real network data,
 * and dropping them once the miss was visible is the exact move this corpus
 * exists to avoid. The report instead quotes the per-recipe rate twice, over the
 * whole census and over the 171 rows carrying at least two ingredient lines — a
 * structural cut, fixed before any match outcome was looked at.
 *
 * Real duplicates are kept too: seven identical "Simple Syrup" rows and two
 * "Apple Roses" from the same authors. Deduplicating would have flattered the
 * per-recipe rate, since both resolve cleanly.
 *
 * ── THE ID PREFIX IS DELIBERATELY NOT `seed-` ────────────────────────────────
 *
 * `1787000664088_dev_recipes.ts` keys its rows `seed-<slug>` and prunes with
 * `where id like 'seed-%'`, deleting every match that is not in ITS OWN corpus.
 * kysely-ctl tracks no seed state, so `seed run` runs both files every time and
 * a human can run either alone. A `seed-` key here would therefore be silently
 * deleted by the other file. Hence `netseed-`, and each seed prunes only its own
 * prefix. Recipe ids are atproto rkeys, where `-` is legal, so this is a valid
 * id and not a shape the app has to special-case (AGENTS.md).
 *
 * ── IDEMPOTENCE ──────────────────────────────────────────────────────────────
 *
 * Same contract as the other corpus, for the same reasons. Ids are deterministic
 * (`netseed-<author>-<slug>`), the `recipe` row is UPSERTED rather than
 * delete-then-inserted because `meal_plan_entry.recipe_id` is ON DELETE RESTRICT
 * and `grocery_item_source.recipe_id` is ON DELETE SET NULL, and the ingredient
 * rows — which have no inbound foreign keys — are replaced wholesale so ordinals
 * stay dense. Re-running is safe; running it twice is safe.
 *
 * Rows are written `origin='local'`, `visibility='private'`, with no `did`,
 * `rkey` or `uri`. They came from a sweep but must not claim to be `sync` rows:
 * the reconciler owns those and would eventually notice these have no record
 * behind them. It also means no identifier reaches the database.
 *
 * ── SEEDS ARE MANUAL, ALWAYS ────────────────────────────────────────────────
 *
 * Nothing runs this on its own and nothing may be taught to — same contract as
 * the other seed. A human types the command or the corpus does not exist.
 */

/** Every recipe id this seed owns starts with this. NOT `seed-`; see above. */
const ID_PREFIX = "netseed-";

/** One recipe, exactly as its author wrote it, minus prose and identity. */
interface NetworkRecipe {
  /** `<author>-<slug>`; `ID_PREFIX` is prepended when the row is written. */
  id: string;
  /** Opaque per-author key (`a01`..`a39`). 39 authors, 210 recipes — the
   *  clustering is real and a per-line confidence interval that ignores it is
   *  too narrow. */
  author: string;
  name: string;
  recipeYield: string | null;
  /** ISO-8601 duration exactly as the `recipe` table stores it, or null. */
  totalTime: string | null;
  /** Verbatim. Section headers included — `parseIngredientLine` flags them and
   *  the measurement excludes them, and how many there are is worth knowing. */
  ingredients: string[];
}

