/**
 * kysely-ctl hands us a live `Kysely` built from `kysely.config.ts` — which is
 * also where `services/web/.env` is loaded and where the pool is torn down
 * afterwards. So there is no connection code here at all.
 */
export async function seed(db: Kysely<DB>): Promise<void> {
  // Every household, not just the active one: anyone testing the
  // household-switching paths has several and wants the corpus visible from all.
  const households = await db.selectFrom("household").select(["id", "name", "created_by_did"]).where("deleted_at", "is", null).orderBy("created_at").execute();

  if (households.length === 0) {
    // Not an error. A fresh dev database legitimately has no households — the
    // first one is created by signing in — and failing here would look like a
    // broken seed rather than a missing step.
    process.stdout.write(
      "\nNo households found, so there is nowhere to put these recipes.\n\n" +
        "  Sign in at http://127.0.0.1:3000/login as chef.test first (127.0.0.1, never\n" +
        "  localhost — atproto forbids `.localhost` in web client_ids), then run\n" +
        "  `pnpm --filter @buttery/web db:seed:run` again.\n\n",
    );
    return;
  }

  await pruneStaleNetworkRecipes(db, new Set(NETWORK_RECIPES.map((r) => `${ID_PREFIX}${r.id}`)));

  let ingredientCount = 0;
  let attachments = 0;

  // One transaction for the whole corpus: a half-seeded database is harder to
  // reason about than an unseeded one.
  await db.transaction().execute(async (trx) => {
    for (const recipe of NETWORK_RECIPES) {
      const id = `${ID_PREFIX}${recipe.id}`;

      await trx
        .insertInto("recipe")
        .values({
          // 'local' and never 'sync', and no did/rkey/uri: see the header. The
          // reconciler owns 'sync' rows and would notice these have no record.
          id,
          origin: "local",
          visibility: "private",
          name: recipe.name,
          recipe_yield: recipe.recipeYield,
          total_time: recipe.totalTime,
          total_time_seconds: durationSeconds(recipe.totalTime),
        })
        .onConflict((oc) =>
          oc.column("id").doUpdateSet({
            name: recipe.name,
            recipe_yield: recipe.recipeYield,
            total_time: recipe.totalTime,
            total_time_seconds: durationSeconds(recipe.totalTime),
          }),
        )
        .execute();

      // Replace rather than upsert, so shortening a recipe cannot leave orphaned
      // high ordinals behind. `recipe_ingredient` has no inbound FK, so this is
      // safe in a way deleting the `recipe` row is not.
      await trx.deleteFrom("recipe_ingredient").where("recipe_id", "=", id).execute();
      if (recipe.ingredients.length > 0) {
        await trx
          .insertInto("recipe_ingredient")
          .values(recipe.ingredients.map((text, ordinal) => ({ recipe_id: id, ordinal, text })))
          .execute();
        ingredientCount += recipe.ingredients.length;
      }

      // No `recipe_instruction` rows at all — instructions were dropped on
      // purpose (see the header). An empty instruction list is a legal recipe.

      for (const household of households) {
        // `added_by_did` is provenance and NOT NULL; the household's creator is
        // the only did this seed can honestly claim. The real author's did is
        // deliberately not carried into the repo.
        const res = await trx
          .insertInto("household_recipe")
          .values({ household_id: household.id, recipe_id: id, added_by_did: household.created_by_did })
          .onConflict((oc) => oc.columns(["household_id", "recipe_id"]).doNothing())
          .execute();
        attachments += Number(res[0]?.numInsertedOrUpdatedRows ?? 0n);
      }
    }
  });

  const authors = new Set(NETWORK_RECIPES.map((r) => r.author)).size;
  process.stdout.write(
    `\nSeeded ${NETWORK_RECIPES.length} network recipes from ${authors} authors\n` +
      `  ${ingredientCount} ingredient lines, verbatim\n` +
      `  ${households.length} household(s): ${households.map((h) => h.name).join(", ")}\n` +
      `  ${attachments} new household attachment(s) this run (the rest were already boxed)\n\n`,
  );
}

/** `PT1H30M` → 5400. Anything it does not recognize becomes null, which the
 *  schema already allows. */
function durationSeconds(iso: string | null): number | null {
  const m = /^PT(?:(\d+)H)?(?:(\d+)M)?(?:(\d+)S)?$/.exec(iso ?? "");
  if (!m) return null;
  const seconds = Number(m[1] ?? 0) * 3600 + Number(m[2] ?? 0) * 60 + Number(m[3] ?? 0);
  return seconds > 0 ? seconds : null;
}

/**
 * Drop `netseed-` recipes left over from an earlier version of this corpus.
 *
 * Scoped to THIS seed's prefix and no wider — the other corpus prunes `seed-%`
 * and the two must never reach into each other's rows.
 *
 * Best-effort by design: `meal_plan_entry.recipe_id` is ON DELETE RESTRICT, so a
 * retired recipe somebody has put on a meal plan cannot be deleted, and that must
 * not stop the rest of the seed from running. Warn and move on.
 */
async function pruneStaleNetworkRecipes(db: Kysely<DB>, keep: Set<string>): Promise<void> {
  const existing = await db.selectFrom("recipe").select("id").where("id", "like", `${ID_PREFIX}%`).execute();
  const stale = existing.map((r) => r.id).filter((id) => !keep.has(id));
  if (stale.length === 0) return;

  try {
    await db.transaction().execute(async (trx) => {
      // household_recipe → recipe is ON DELETE RESTRICT, so the box rows go first.
      await trx.deleteFrom("household_recipe").where("recipe_id", "in", stale).execute();
      await trx.deleteFrom("recipe").where("id", "in", stale).execute();
    });
    process.stdout.write(`Removed ${stale.length} stale network recipe(s) no longer in the corpus.\n`);
  } catch (err) {
    process.stdout.write(`Could not remove ${stale.length} stale network recipe(s) (${err instanceof Error ? err.message : String(err)}); leaving them in place.\n`);
  }
}
